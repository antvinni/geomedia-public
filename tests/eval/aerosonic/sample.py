"""The fixed sample for the real-audio curve test, drawn from sample_meta.csv alone (no audio is
looked at), and the eval manifest for it. Stdlib only.

  python -I sample.py MEDIA_DIR    writes sample.csv here and ../aerosonic.toml

Strata (subclass 1 piston, 2 turboprop, 3 turbofan, 4 rotorcraft; location 0 = 15.5 km from the
runway, 1–2 = beside it): every piston and rotorcraft clip, every turboprop and turbofan clip
from locations 1–2, and 40 turboprop and 40 turbofan clips drawn from location 0.
"""
import csv
import os
import random
import sys

SEED = 20261106
FAR_N = 40
STRATA = ["piston-all", "rotor-all", "low-turboprop", "low-turbofan", "far-turboprop", "far-turbofan"]


def stratum(r):
    sub, loc = r["subclass"], r["location"]
    if sub == "1":
        return "piston-all"
    if sub == "4":
        return "rotor-all"
    near = loc in ("1", "2")
    if sub == "2":
        return "low-turboprop" if near else "far-turboprop"
    if sub == "3":
        return "low-turbofan" if near else "far-turbofan"
    return None


def draw(meta_rows, seed):
    """The sampled aircraft clips, each row plus its `stratum`, in stratum then filename order."""
    pools = {s: [] for s in STRATA}
    for r in meta_rows:
        if r["class"] != "1":
            continue
        s = stratum(r)
        if s:
            pools[s].append(dict(r, stratum=s))
    out = []
    for s in STRATA:
        pool = sorted(pools[s], key=lambda r: r["filename"])
        if s.startswith("far-"):
            pool = sorted(random.Random(seed).sample(pool, FAR_N), key=lambda r: r["filename"])
        out.extend(pool)
    return out


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_manifest(sample, env_files, out_path):
    """The `curves` manifest: every sampled clip, then the six 1-hour recordings."""
    lines = [
        "# Real-audio Doppler-curve test: AeroSonicDB YPAD-0523 v1.1.1 (B. Downward, Zenodo 8371595,",
        "# CC BY-NC 4.0 — non-commercial evaluation only). Generated by tests/eval/aerosonic/sample.py",
        f"# (seed {SEED}); never edit by hand. Media and marks live in the kept-data folder",
        "# (media:aerosonic/), never in git. Truth = curves marked on a plain spectrogram before",
        "# discovery ran (tests/eval/aerosonic/marks.sha256). Design:",
        "# docs/superpowers/specs/2026-11-06-real-curve-test-design.md",
        "",
    ]
    for r in sample:
        stem = r["filename"][:-4]
        off, dur = float(r["offset"]), float(r["duration"])
        lines += [
            "[[case]]",
            f"id = {q(stem)}",
            'kind = "curves"',
            f"media = {q('media:aerosonic/audio/' + r['filename'])}",
            f"marks = {q('media:aerosonic/marks/' + stem + '.json')}",
            'marks_hashes = "aerosonic/marks.sha256"',
            f"engine = {q(r['engtype'])}",
            f"site = {int(r['location'])}",
            f"stratum = {q(r['stratum'])}",
            f"audible = [{off}, {off + dur}]",
            f"truth_note = {q(r['typedesig'] + ' ' + r['engtype'] + ', site ' + r['location'] + ', ' + r['altitude'] + ' ft')}",
            "",
        ]
    for k, fn in enumerate(env_files):
        stem = fn[:-4]
        lines += [
            "[[case]]",
            f"id = {q('env-' + str(k) + '-' + stem)}",
            'kind = "curves"',
            f"media = {q('media:aerosonic/env_audio/' + fn)}",
            f"marks = {q('media:aerosonic/marks/' + stem + '.json')}",
            'marks_hashes = "aerosonic/marks.sha256"',
            'labels_csv = "media:aerosonic/environment_class_mappings.csv"',
            f"labels_column = {k}",
            'truth_note = "continuous 1 h urban recording"',
            "",
        ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))


def write_sample_csv(sample, path):
    keys = ["filename", "stratum", "engtype", "typedesig", "location", "altitude", "offset", "duration"]
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys, extrasaction="ignore")
        w.writeheader()
        w.writerows(sample)


if __name__ == "__main__":
    media = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(media, "aerosonic", "sample_meta.csv"), newline="") as f:
        rows = list(csv.DictReader(f))
    s = draw(rows, SEED)
    env_dir = os.path.join(media, "aerosonic", "env_audio")
    sys.path.insert(0, here)
    import envmap

    env = envmap.env_files(env_dir)
    write_sample_csv(s, os.path.join(here, "sample.csv"))
    write_manifest(s, env, os.path.join(here, "..", "aerosonic.toml"))
    print(f"{len(s)} clips, {len(env)} continuous recordings")
