"""Write tests/eval/aerosonic-detect.toml: stage-1 detection cases for AeroSonicDB.

The six 1-h recordings (hours 1–3 = tuning, 4–6 = test) and every labelled aircraft clip (its own
train/test column → tuning/test; floor_limited when the audible window covers > 70 % of the
clip). The 10-s background clips are left out: shorter than the detector's minimum pass, they
can never hold a pass, so they would test nothing.

usage: detect_manifest.py MEDIA_ROOT OUT_TOML   (MEDIA_ROOT = the kept-data media folder)
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import envmap  # noqa: E402


def main():
    media_root, out = sys.argv[1], sys.argv[2]
    aero = os.path.join(media_root, "aerosonic")
    lines = [
        "# Stage-1 detection on AeroSonicDB (B. Downward, Zenodo 8371595, CC BY-NC 4.0; non-commercial",
        "# evaluation only). Generated by tests/eval/aerosonic/detect_manifest.py — do not edit.",
        "# Tune only on split = \"tuning\"; \"test\" is report-only.",
        "",
    ]
    for k, name in enumerate(envmap.env_files(os.path.join(aero, "env_audio"))):
        stem = os.path.splitext(name)[0]
        lines += [
            "[[case]]",
            f'id = "env-{stem}"',
            'kind = "detect"',
            f'media = "media:aerosonic/env_audio/{name}"',
            'labels_csv = "media:aerosonic/environment_class_mappings.csv"',
            f"labels_column = {k}",
            f'split = "{"tuning" if k < 3 else "test"}"',
            'truth_note = "continuous 1 h recording, 5-s labels"',
            "",
        ]
    with open(os.path.join(aero, "sample_meta.csv"), newline="") as f:
        for r in csv.DictReader(f):
            if r["class"] != "1":
                continue
            off, dur, length = float(r["offset"]), float(r["duration"]), float(r["file_length"])
            lines += [
                "[[case]]",
                f'id = "{os.path.splitext(r["filename"])[0]}"',
                'kind = "detect"',
                f'media = "media:aerosonic/audio/{r["filename"]}"',
                f"audible = [{off}, {off + dur}]",
                f'engine = "{r["engtype"]}"',
                f'split = "{"tuning" if r["train-test"] == "train" else "test"}"',
                f"floor_limited = {'true' if dur > 0.7 * length else 'false'}",
                "",
            ]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
