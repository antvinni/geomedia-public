"""Write tests/eval/street-detect.toml: the street recordings' stage-1 cases plus every
AeroSonicDB detect case, so one sweep judges street sounds and the airport hours together.

usage: make_manifest.py OUT_TOML   (run from anywhere; reads ../aerosonic-detect.toml)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AERO = os.path.join(HERE, "..", "aerosonic-detect.toml")

STREET = [
    ("street-phone", "media:phone/clip.mp4", "media:phone/labels.csv",
     "tuning", "phone clip, 10 min, labels from the blind marks"),
    ("street-piccadilly", "media:street/piccadilly.webm", "media:street/piccadilly-labels.csv",
     "tuning", "Piccadilly street walk 5 min, labels from blind marks"),
    ("street-oysterbay", "media:oysterbay/raw.webm", "media:oysterbay/labels.csv",
     "test", "Oyster Bay 1 h, labels from ADS-B passes (development: also the location veto)"),
]


def main():
    out = sys.argv[1]
    lines = [
        "# Stage-1 detection on street recordings and AeroSonicDB. Generated by",
        "# tests/eval/street/make_manifest.py — do not edit. Media and labels stay in the media",
        "# folder; their hashes are in tests/eval/street/labels.sha256. AeroSonicDB: B. Downward,",
        "# Zenodo 8371595, CC BY-NC 4.0; non-commercial evaluation only.",
        "# Tune only on split = \"tuning\"; \"test\" is the check split, run once.",
        "",
    ]
    for cid, media, labels, split, note in STREET:
        lines += [
            "[[case]]",
            f'id = "{cid}"',
            'kind = "detect"',
            f'media = "{media}"',
            f'labels_csv = "{labels}"',
            "labels_column = 0",
            f'split = "{split}"',
            f'truth_note = "{note}"',
            "",
        ]
    with open(AERO) as f:
        aero = f.read()
    body = aero[aero.index("[[case]]"):]
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n" + body)
    print(f"{out}: {len(STREET)} street cases + {body.count('[[case]]')} AeroSonicDB cases")


if __name__ == "__main__":
    main()
